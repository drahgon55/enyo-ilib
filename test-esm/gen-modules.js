#!/usr/bin/env node
// Regenerates modules.js, the list all-modules.html cold-loads.
//   node test-esm/gen-modules.js
const fs = require('fs'), path = require('path');
const ROOT = path.dirname(__dirname);

// NodeLoader.js imports the bare Node specifiers `fs` and `util`, so it cannot
// resolve in a browser. Nothing in the package imports it, so that is harmless
// -- but it must be excluded here or it would fail every run for a reason that
// is not a defect.
const EXCLUDE = new Set(['ilib/lib/NodeLoader.js']);

function walk(dir, out = []) {
	for (const e of fs.readdirSync(dir, {withFileTypes: true}).sort((a, b) => a.name < b.name ? -1 : 1)) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) walk(p, out);
		else if (e.name.endsWith('.js')) out.push(path.relative(ROOT, p));
	}
	return out;
}

const list = walk(path.join(ROOT, 'src'))
	.concat(walk(path.join(ROOT, 'ilib/lib')))
	.concat(['index.js'])
	.filter(f => !EXCLUDE.has(f))
	.map(f => '../' + f);

fs.writeFileSync(path.join(__dirname, 'modules.js'),
	'// Generated by gen-modules.js -- every module under src/ and ilib/lib,\n' +
	'// plus index.js. ilib/locale is 3556 JSON data files and holds no code.\n' +
	'export default ' + JSON.stringify(list, null, 1) + ';\n');
console.log('listed ' + list.length + ' modules');
